macro_rules! same_errno {
    ($($name:ident),* $(,)?) => {
        $(const _: () = assert!(libc::$name == kernel_abi::$name.raw());)*
    };
}

macro_rules! same_value {
    ($($c:path = $kernel:expr),* $(,)?) => {
        $(const _: () = assert!($c == $kernel);)*
    };
}

